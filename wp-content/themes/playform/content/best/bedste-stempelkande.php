<h3>Glas eller stål</h3>
<p>En stempelkande i glas er klassikeren. Du kan følge kaffen, mens den trækker, og glasset giver ikke smag af sig. Til gengæld kan det gå i stykker, og kaffen køler hurtigere af. En stempelkande i stål er mere robust og holder ofte bedre på varmen – særligt hvis den har dobbelte vægge. Den er det sikre valg på tur og i et travlt køkken.</p>
<h3>Størrelse: kopper og liter</h3>
